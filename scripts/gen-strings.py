#!/usr/bin/env python3
"""Regenerate Resources/{en,zh-Hans}.lproj/Localizable.strings from
scripts/l10n_table.py (app keys) + Sources/DiskScanCore/ReasonText.swift
(English core templates) + the core Chinese table. Box/dev tool; writes only
those two files. The committed .strings files are the source of truth for the
app; tests check them, so this script is optional."""
import os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "scripts"))
from l10n_table import APP, CORE_ZH

def core_english():
    src = open(os.path.join(ROOT, "Sources/DiskScanCore/ReasonText.swift"), encoding="utf-8").read()
    consts = dict(re.findall(r'public static let (\w+) = "((?:[^"\\]|\\.)*)"', src))
    out = {}
    for k, v in re.findall(r'^\s*"([a-z]+\.[A-Za-z.]+)":\s*(.+?),\s*$', src, re.M):
        if v.startswith('"'): out[k] = v[1:-1].replace('\\"', '"')
        else: out[k] = consts[v.split(".")[-1]]
    return out

def esc(s): return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")

def write(lang, pairs):
    d = os.path.join(ROOT, "Resources", f"{lang}.lproj"); os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, "Localizable.strings"), "w", encoding="utf-8") as f:
        f.write(f"/* DiskRings — {lang}. Generated by scripts/gen-strings.py; keys are stable identifiers. */\n\n")
        for k, v in pairs: f.write(f'"{esc(k)}" = "{esc(v)}";\n')

core = core_english()
assert set(core) == set(CORE_ZH), set(core) ^ set(CORE_ZH)
write("en", [(k, e) for k, e, _ in APP] + sorted(core.items()))
write("zh-Hans", [(k, z) for k, _, z in APP] + sorted((k, CORE_ZH[k]) for k in core))
print(f"{len(APP) + len(core)} keys per language")
